import { qualitiesForTarget } from "@/data/qualities";
import type { AnalogSite, Similarity, Strength, Target } from "@/types/site";
import type { DiscoveryProvider, DiscoveryQuery } from "./DiscoveryProvider";

export const MOCK_PROVIDER_ID = "mock-test-data";

/**
 * TEST DATA ONLY. Returns three synthetic candidates so the pipeline can be checked end to end
 * (amber pins, ranking, side-panel warning, favourites). No analysis is performed and the
 * locations are arbitrary. Each candidate exercises a different path:
 *   A: strong on every requested quality (should rank near the top),
 *   B: moderate on every requested quality,
 *   C: lists the first requested quality as a LIMITATION, so it must never match that filter.
 */
const BASE: { key: "a" | "b" | "c"; lat: number; lon: number; country: string; confidence: number; strength: Strength }[] = [
  { key: "a", lat: -23.4, lon: 15.2, country: "Namibia (synthetic test location)", confidence: 0.81, strength: "strong" },
  { key: "b", lat: 44.6, lon: 98.9, country: "Mongolia (synthetic test location)", confidence: 0.57, strength: "moderate" },
  { key: "c", lat: -31.9, lon: 135.1, country: "Australia (synthetic test location)", confidence: 0.34, strength: "partial" },
];

function candidate(base: (typeof BASE)[number], query: DiscoveryQuery, runAt: string): AnalogSite {
  const t: Target = query.target;
  const requested = query.qualityIds.length ? query.qualityIds : qualitiesForTarget(t).slice(0, 2).map((q) => q.id);
  const excluded = base.key === "c" ? requested[0] : undefined;
  const similarities: Similarity[] = requested
    .filter((q) => q !== excluded)
    .map((qualityId) => ({ qualityId, target: t, strength: base.strength, explanation: "TEST DATA: synthetic similarity generated by the mock provider." }));
  return {
    id: `test-candidate-${base.key}-${t}`,
    name: `[TEST DATA] Mock candidate ${base.key.toUpperCase()}`,
    country: base.country,
    lat: base.lat,
    lon: base.lon,
    origin: "hypatia_candidate",
    programs: [],
    targets: [t],
    summary:
      "TEST DATA. Synthetic candidate produced by the mock discovery provider to test the pipeline. It is not a real analog proposal and no dataset was analysed.",
    similarities,
    limitations: [
      ...(excluded
        ? [{ qualityId: excluded, target: t, explanation: "TEST DATA: deliberately listed as a limitation to check that limitations exclude candidates too." }]
        : []),
      { target: t, explanation: "TEST DATA: unverified; no field or literature confirmation exists." },
      { target: t, explanation: "TEST DATA: location is arbitrary." },
    ],
    researchUse: [],
    images: { earth: [], target: [] },
    references: [],
    discovery: {
      providerId: MOCK_PROVIDER_ID,
      runAt,
      confidence: base.confidence,
      datasetsUsed: ["None (TEST DATA)"],
      method: "Mock provider for pipeline testing; no analysis performed.",
      status: "unverified",
    },
  };
}

export const mockDiscoveryProvider: DiscoveryProvider = {
  id: MOCK_PROVIDER_ID,
  name: "Mock provider (TEST DATA)",
  isTestData: true,
  async run(query) {
    // Simulate a short computation so loading states are visible.
    await new Promise((r) => setTimeout(r, 400));
    const runAt = new Date().toISOString();
    return BASE.map((b) => candidate(b, query, runAt));
  },
};
